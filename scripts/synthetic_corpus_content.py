"""Fictional text the synthetic corpus is assembled from.

This module holds only content: invented companies and the Markdown templates for each section of
an annual-report-style document. ``gen_synthetic_corpus.py`` holds the logic that draws figures,
fills these templates, and writes files. The split keeps both modules small (AGENTS.md) and makes
the boundary obvious: change prose here, change behavior there.

Every name, place, segment, and risk below is invented. Tickers end in ``.TEST`` so they cannot be
read as listed symbols, and contact placeholders use the reserved ``example.com`` domain and the
``555-01xx`` telephone block set aside for fiction.

Templates are ``str.format`` strings; ``gen_synthetic_corpus._document_values`` supplies every key.
Paragraphs are re-wrapped when rendered, so the line breaks here do not reach the output. Blocks
beginning with ``|``, ``-``, ``#``, or ``>`` are emitted verbatim, which is how tables, list items,
and risk subheadings survive.
"""

