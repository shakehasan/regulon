@dataclass(frozen=True)
class CompanyProfile:
    """A fictional issuer the generator writes filings for.

    Attributes:
        name: Invented company name, used in headings and front matter.
        ticker: Invented ticker; always ends in ``.TEST`` so it cannot be a listed symbol.
        slug: Uppercase filename fragment identifying the company.
        industry: One-line description of the invented business.
        headquarters: Invented place name for the registered office.
        segments: Reportable segment names; each gets a revenue line in the segment table.
        growth_drivers: Candidate explanations the narrative attributes revenue movement to.
        risks: Company-specific risk factors, as ``###`` subsections.
    """

    name: str
    ticker: str
    slug: str
    industry: str
    headquarters: str
    segments: tuple[str, ...]
    growth_drivers: tuple[str, ...]
    risks: str


FREIGHT_RISKS = """\
### Fuel and Energy Price Volatility

Diesel and electricity are the largest variable inputs in the invented cost base described here.
Contracted fuel surcharges reset quarterly, so a sharp move in energy prices would be absorbed for a
quarter before it could be passed through, compressing margin in the interim.

### Contract Concentration

The ten largest contracts account for a majority of segment revenue in this sample data. Losing one
at renewal, or repricing it downward, would move reported results out of proportion to the volume
involved.

### Network Capacity and Labour Availability

Terminal throughput depends on licensed drivers and yard staff being available where the freight is.
Sustained wage inflation or a shortage of qualified operators would raise the cost of serving
existing volumes and delay the invented expansion described above."""

GRID_RISKS = """\
### Rate Case Outcomes

Allowed returns under the invented regulatory regime described here reset on a multi-year cycle. A
determination below the assumed allowed return would reduce revenue in the regulated segment with no
matching reduction in the obligation to keep investing.

### Storm and Physical Asset Exposure

Overhead distribution assets are exposed to severe weather. Restoration cost is recoverable only in
part and only after review, so a severe season would open a timing gap between the spending and its
recovery.

### Interconnection Backlog

Growth in grid services depends on connecting new generation to the network. Permitting delays or
long equipment lead times would push revenue into later periods even where contracts are signed."""

INSTRUMENT_RISKS = """\
### Instrument Placement Cycles

Instrument revenue is lumpy because laboratory capital budgets are approved annually. Deferring
placements into the following year would depress instrument revenue even when the installed base and
consumables demand are unchanged.

### Single-Source Components

Several assemblies in this invented product line are sourced from a single qualified supplier.
Requalifying an alternative takes multiple quarters, so an interruption would constrain output well
beyond the interruption itself.

### Regulatory Clearance Timelines

Selling into clinical settings depends on clearances from health regulators. A review longer than
the one assumed in these invented plans would delay launches and shift the revenue attached to them
into later fiscal years."""

